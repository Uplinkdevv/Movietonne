// Master set of all fallback items indexed for instant search and lookup
export const ALL_FALLBACK_ITEMS: MediaItem[] = Array.from(
  new Map(
    [...FALLBACK_TRENDING, ...FALLBACK_MOVIES, ...FALLBACK_TV, ...FALLBACK_ANIME].map((item) => [item.id, item])
  ).values()
);

/**
 * Curated fallback season episode generator
 */
export function getFallbackEpisodes(tvId: number, seasonNumber: number): Episode[] {
  const item = ALL_FALLBACK_ITEMS.find((m) => m.tmdbId === tvId);
  const season = item?.seasons?.find((s) => s.seasonNumber === seasonNumber);
  const count = season?.episodeCount || 8;

  const episodes: Episode[] = [];
  for (let i = 1; i <= count; i++) {
    episodes.push({
      id: tvId * 1000 + seasonNumber * 100 + i,
      episodeNumber: i,
      seasonNumber,
      name: `${item ? item.title : 'Show'} - Episode ${i}`,
      overview: `Episode ${i} of Season ${seasonNumber}. The adventure continues as the stakes rise higher.`,
      stillPath: item?.backdropPath || null,
      airDate: '2023-01-01',
      durationMinutes: 48,
    });
  }
  return episodes;
}
